"""Export the agent code from the notebook into app/agents.py.

The notebook stays the place you edit. This copies every code cell from the top of
notebooks/person_c_agents.ipynb up to the "## 11. Demo scenarios" heading into
app/agents.py, which the API and worker import. The demo cells are left out, so
importing the module never runs a claim.

Run after every change to sections 1-10 of the notebook:
    python scripts/export_agents.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTEBOOK = ROOT / "notebooks" / "person_c_agents.ipynb"
TARGET = ROOT / "app" / "agents.py"
STOP_HEADING = "## 11."


def main() -> None:
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    parts = [
        '"""AUTO-GENERATED from notebooks/person_c_agents.ipynb by scripts/export_agents.py.\n'
        'Do not edit this file; edit the notebook and re-export."""\n'
    ]
    stopped = False
    for cell in nb["cells"]:
        src = "".join(cell["source"])
        if cell["cell_type"] == "markdown" and src.lstrip().startswith(STOP_HEADING):
            stopped = True
            break
        if cell["cell_type"] == "code":
            # IPython magics and shell commands are not valid Python in a module
            lines = [l for l in src.splitlines() if not l.lstrip().startswith(("%", "!"))]
            parts.append("\n".join(lines).rstrip() + "\n")
    if not stopped:
        sys.exit(f"Heading '{STOP_HEADING}' not found in {NOTEBOOK.name}; refusing to export demo cells.")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n\n".join(parts), encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)} from {NOTEBOOK.relative_to(ROOT)}")


if __name__ == "__main__":
    main()